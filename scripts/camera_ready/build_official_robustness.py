#!/usr/bin/env python

import os as _os
from pathlib import Path as _Path
# Repository root; override with LEVEE_ROOT if the layout differs.
REPO_ROOT = _Path(_os.environ.get("LEVEE_ROOT", _Path(__file__).resolve().parents[2]))
# Directory holding pre-computed results (see results/README.md).
RESULTS_DIR = _Path(_os.environ.get("LEVEE_RESULTS", REPO_ROOT / "results"))
# Directory holding model weights / diff vectors.
WEIGHTS_DIR = _Path(_os.environ.get("LEVEE_WEIGHTS", REPO_ROOT / "weights"))
# BBQ jsonl (58,492 items). Download instructions in README.
BBQ_JSONL = _Path(_os.environ.get("LEVEE_BBQ", REPO_ROOT / "data" / "bbq_all.jsonl"))

r"""대표 3모델 pilot — legacy L-BBQ vs official BBQ robustness 표 생성.

판정 정의는 emnlp_camera/docs/PILOT_PLAN.md 의 output table 을 그대로 따른다:
  Localization : mid 대표 레이어가 세 대표 레이어(first/mid/last) 중 최저 bias
  Necessity    : minus_mid 가 세 block-removal 조건 중 최대 bias
  Sufficiency  : only_mid 가 세 only-third 조건 중 최저 bias

unassigned 통계는 (example, candidate) 후보 175,476 기준이 아니라
**실제 모델 예측**(ambiguous 29,246개 응답) 기준으로 재계산한다:
legacy determine_bias() 가 None 을 반환한 예측 수.
"""
import json, os, sys, glob, csv

# Pilot outputs (per-example predictions) and pre-computed results.
CAM  = os.environ.get("LEVEE_PILOT_ROOT", str(REPO_ROOT))
ROOT = os.environ.get("LEVEE_RESULTS_ROOT", str(REPO_ROOT))
sys.path.insert(0, str(REPO_ROOT / "src" / "eval"))
from eval_bbq_shared import determine_bias as legacy

bbq = {}
for l in open(os.path.join(ROOT, "data/bbq_all.jsonl"), encoding="utf-8"):
    r = json.loads(l); bbq[(r["category"], r["example_id"])] = r

MODELS = [("Qwen2.5-3B", "qwen_3b"), ("Llama-3.1-8B", "llama31_8b"), ("Gemma-2-9B", "gemma_9b")]
NEC = ("minus_first", "minus_mid", "minus_last")
SUF = ("only_first", "only_mid", "only_last")

rows_csv, tab_rows, un_all = [], [], []
for disp, m in MODELS:
    d = os.path.join(CAM, "results/pilot", m)
    files = sorted(glob.glob(os.path.join(d, "*_official_bbq.json")))
    assert len(files) == 11, (m, len(files))
    S = {}   # cond -> (legacy_score, official_score, layer_desc)
    UN = {}  # cond -> (unassigned_count, rate)
    for f in files:
        cond = os.path.basename(f).replace("_official_bbq.json", "")
        j = json.load(open(f))
        S[cond] = (j["old_metrics"]["ambig"]["bias_score"],
                   j["official_metrics"]["ambig"]["bias_score"],
                   j.get("layer_desc", ""))
        # 실제 예측 기준 unassigned
        n_amb = n_un = 0
        for line in open(f.replace("_official_bbq.json", "_examples.jsonl"), encoding="utf-8"):
            e = json.loads(line)
            if e["context_condition"] != "ambig":
                continue
            n_amb += 1
            item = bbq[(e["category"], e["example_id"])]
            if legacy(item, e["prediction_index"]) is None:
                n_un += 1
        assert n_amb == 29246, (m, cond, n_amb)
        UN[cond] = (n_un, n_un / n_amb)
        un_all.append((disp, cond, n_un, n_un / n_amb))
        rows_csv.append(dict(model=disp, condition=cond,
                             legacy_lbbq=S[cond][0], official_bbq=S[cond][1],
                             unassigned=n_un, unassigned_rate=round(n_un / n_amb, 6)))
    rep = {t: next(c for c in S if c.endswith(f"_{t}_rep")) for t in ("first", "mid", "last")}
    verd = {}
    for tag, k in (("L-BBQ", 0), ("official", 1)):
        loc = S[rep["mid"]][k] < S[rep["first"]][k] and S[rep["mid"]][k] < S[rep["last"]][k]
        nec = max(NEC, key=lambda c: S[c][k]) == "minus_mid"
        suf = min(SUF, key=lambda c: S[c][k]) == "only_mid"
        verd[tag] = (loc, nec, suf)
    assert verd["L-BBQ"] == verd["official"] == (True, True, True), (m, verd)

    def cell(conds, k, best, best_fn):
        out = []
        for c in conds:
            v = f"{S[c][k]:.3f}"
            if best_fn(conds, key=lambda x: S[x][k]) == c:
                v = r"\textbf{%s}" % v
            out.append(v)
        return " / ".join(out)
    # 표에는 block-level 두 판정만 싣는다. 대표 레이어 열은 official scorer 로
    # exhaustive per-layer sweep 을 재검증한 것이 아니므로 주장 범위에서 제외한다.
    for tag, k in (("L-BBQ", 0), ("Official", 1)):
        first = disp if tag == "L-BBQ" else ""
        tab_rows.append(
            f"{first} & {tag} & "
            + cell(NEC, k, 'minus_mid', max) + " & "
            + cell(SUF, k, 'only_mid', min) + r" \\")
    if disp != MODELS[-1][0]:
        tab_rows.append(r"\midrule")

os.makedirs(os.path.join(ROOT, "paper/generated"), exist_ok=True)
with open(os.path.join(ROOT, "paper/generated/tab_official_robustness.tex"), "w") as f:
    f.write("% GENERATED by scripts/camera_ready/build_official_robustness.py -- do not edit\n")
    f.write("\n".join(tab_rows) + "\n")
out_csv = os.path.join(CAM, "results/pilot/robustness_summary_20260826.csv")
with open(out_csv, "w", newline="") as f:
    w = csv.DictWriter(f, fieldnames=list(rows_csv[0])); w.writeheader(); w.writerows(rows_csv)

print("판정: 3모델 전부 (loc, nec, suf) = (True, True, True), L-BBQ/official 동일  [assert 통과]")
rates = [r for _, _, _, r in un_all]
tot_un = sum(n for _, _, n, _ in un_all); tot = 29246 * len(un_all)
print(f"\nunassigned (실제 예측, ambiguous 29,246/조건, 33조건):")
print(f"  조건별 최소 {min(rates):.2%}  최대 {max(rates):.2%}  전체 가중평균 {tot_un/tot:.2%}")
lo = min(un_all, key=lambda x: x[3]); hi = max(un_all, key=lambda x: x[3])
print(f"  최소: {lo[0]} {lo[1]} {lo[2]:,} ({lo[3]:.2%})   최대: {hi[0]} {hi[1]} {hi[2]:,} ({hi[3]:.2%})")
print(f"\n-> paper/generated/tab_official_robustness.tex")
print(f"-> {out_csv}")
