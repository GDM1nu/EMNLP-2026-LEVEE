#!/usr/bin/env python
r"""Camera-ready appendix table generator (LEVEE, EMNLP 2026).

모든 수치는 raw json에서 직접 읽는다. 손으로 옮겨적은 값은 하나도 없다.
출력: paper/generated/*.tex  (main.tex 가 \input 한다)

주의 — CAMERA_READY_TODO.md §B 데이터 경로의 함정:
  final_58k_20260711/results/        는 이름과 달리 8k subsample 이다. BBQ 는 절대 여기서 읽지 않는다.
  final_58k_20260711/results_full58k/ 가 BBQ 정본. MMLU 는 lm_eval 고정셋이라 results/ 가 정본.

지표 규약(§B X-2 주의): 국소화는 언제나 ambiguous-context bias_score 로 정의한다.
overall accuracy 로 집계하면 Mistral-24B 의 third argmin 이 first 로 뒤집힌다.
"""
import json, os

# Paths resolve to the repository root by default; override with env vars.
# Pre-computed results are not redistributed here (see results/README.md).
ROOT = os.environ.get("LEVEE_RESULTS_ROOT") or os.environ.get(
    "LEVEE_ROOT", os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
OUT  = os.environ.get("LEVEE_TABLES", os.path.join(
    os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))), "paper", "generated"))
os.makedirs(OUT, exist_ok=True)

def J(*p):
    with open(os.path.join(ROOT, *p)) as f:
        return json.load(f)

def W(name, body):
    with open(os.path.join(OUT, name), "w") as f:
        f.write("% GENERATED by scripts/camera_ready/build_appendix.py -- do not edit by hand\n")
        f.write(body.rstrip() + "\n")
        # \bottomrule must live in the same \input'd file as the last row's \\ --
        # \noalign (which \bottomrule expands to) is only recognized by \halign
        # immediately after \cr, and that check does not survive an \input file
        # boundary. Keeping \bottomrule out of this file reproduces "Misplaced
        # \noalign" / cascading "Missing }" errors on compile. Verified empirically.
        f.write("\\bottomrule\n")
    print(f"  wrote {os.path.join(OUT, name)}")

CONDS = ["full", "minus_first", "minus_mid", "minus_last",
         "only_first", "only_mid", "only_last"]
BBQ58K = "results/rebuttal3/final_58k_20260711/results_full58k"
BLOCK  = "results/block_removal"
MMLU58 = "results/rebuttal3/final_58k_20260711/results"

NEW_MODELS = [
    # DeepSeek-LLM-7B 는 사용자 지시로 제외한다. 약속문(i)이 명시한 모델은 아래 4개뿐이고,
    # DeepSeek 은 그 범위 밖이다. 다시 넣지 말 것.
    ("Mistral-7B",         "Mistral", f"{BLOCK}/mistral_7b",        f"{BLOCK}/mistral_7b"),
    ("Mistral-Small-24B",  "Mistral", f"{BLOCK}/mistral_small_24b", f"{MMLU58}/mistral-small-24b"),
    ("Qwen2.5-32B",        "Qwen",    f"{BBQ58K}/qwen2.5-32b",      f"{MMLU58}/qwen2.5-32b"),
    ("Gemma-4-31B",        "Gemma",   f"{BBQ58K}/gemma-4-31b",      f"{MMLU58}/gemma-4-31b"),
]

def bbq_metrics(d, cond):
    return J(d, f"block_{cond}_bbq.json")["metrics"]

def bbq(d, cond):
    m = bbq_metrics(d, cond)
    return m["ambig"]["bias_score"], m["overall"]["total"]

def mmlu(d, cond):
    for name in (f"block_{cond}_mmlu.json", f"block_{cond}_mmlu_full.json"):
        if os.path.exists(os.path.join(ROOT, d, name)):
            return J(d, name)["mmlu_acc"]
    return None

def fmt(x, nd=4):
    return "---" if x is None else f"{x:.{nd}f}"

# ══════════════════ X-1 ══════════════════════════════════════
def build_x1():
    rows_b, rows_m, audit, verdict = [], [], [], []
    for name, fam, bd, md in NEW_MODELS:
        vals, totals = {}, set()
        for c in CONDS:
            v, t = bbq(bd, c); vals[c] = v; totals.add(t)
        audit.append((name, sorted(totals)))
        onlys = {c: vals[c] for c in ("only_first", "only_mid", "only_last")}
        minus = {c: vals[c] for c in ("minus_first", "minus_mid", "minus_last")}
        bs, bn = min(onlys, key=onlys.get), max(minus, key=minus.get)
        verdict.append((name, bs == "only_mid", bn == "minus_mid"))
        cells = [(r"\textbf{%s}" % fmt(vals[c])) if c in (bs, bn) else fmt(vals[c]) for c in CONDS]
        rows_b.append(f"{name} & " + " & ".join(cells) + r" \\")
        if md:
            mv = {c: mmlu(md, c) for c in ("full", "minus_first", "minus_mid", "minus_last")}
            if any(v is not None for v in mv.values()):
                rows_m.append(f"{name} & " + " & ".join(
                    fmt(mv[c], 3) for c in ("full", "minus_first", "minus_mid", "minus_last")) + r" \\")
    return rows_b, rows_m, audit, verdict

# ══════════════════ Y ════════════════════════════════════════
DISPLAY = {"qwen_0.5b":"Qwen2.5-0.5B","qwen_1.5b":"Qwen2.5-1.5B","qwen_3b":"Qwen2.5-3B",
           "qwen_14b":"Qwen2.5-14B","gemma_2b":"Gemma-2-2B","gemma_9b":"Gemma-2-9B",
           "gemma3_12b":"Gemma-3-12B","llama32_1b":"Llama-3.2-1B","llama32_3b":"Llama-3.2-3B",
           "llama31_8b":"Llama-3.1-8B","llama3_8b":"Llama-3-8B"}
ORDER = ["qwen_0.5b","qwen_1.5b","qwen_3b","qwen_14b","gemma_2b","gemma_9b","gemma3_12b",
         "llama32_1b","llama32_3b","llama31_8b","llama3_8b"]

def build_y():
    d = J("results/rebuttal2/bootstrap_ci.json")
    want = ["minus_mid - full", "only_mid - base", "minus_mid - base"]
    rows, n_excl, n_pos = [], {w: 0 for w in want}, {w: 0 for w in want}
    for k in ORDER:
        cs, cells = d[k]["contrasts"], []
        for w in want:
            c = cs[w]; lo, hi = c["ci95"]; excl = c["excludes_zero"]
            assert excl == ((lo > 0) or (hi < 0)), (k, w)     # 저장값 ↔ CI 재계산 교차검증
            n_excl[w] += excl
            n_pos[w]  += (lo > 0)
            s = f"${c['delta']:+.4f}$ [${lo:+.4f}$, ${hi:+.4f}$]"
            cells.append(r"\textbf{" + s + "}" if excl else s)
        rows.append(f"{DISPLAY[k]} & " + " & ".join(cells) + r" \\")
    return rows, n_excl, n_pos

# ══════════════════ X-2 ══════════════════════════════════════
def build_x2():
    d = J("results/appendix_x2/x2_per_layer_agg.json")
    rows, stat = [], {}
    for key, disp in (("mistral_7b", "Mistral-7B"), ("mistral_small_24b_full58k", "Mistral-Small-24B")):
        m = d[key]; rows_l = m["rows"]; b = m["bounds"]
        for r in rows_l:                                      # 무결성: 전 레이어 full 58k
            assert r["n_eval"] == 58492 and r["parse_rate"] == 1.0, (key, r["L"])
        peak = min(rows_l, key=lambda r: r["bias"])
        means = {t: sum(r["bias"] for r in rows_l if r["third"] == t) /
                    sum(1 for r in rows_l if r["third"] == t) for t in ("first", "mid", "last")}
        argmin = min(means, key=means.get)
        stat[disp] = dict(n=m["n_layers"], peak=peak["L"], peak_third=peak["third"],
                          peak_bias=peak["bias"], means=means, argmin=argmin)
        rng = lambda t: f"{b[t][0]}--{b[t][1]}"
        rows.append(f"{disp} & {m['n_layers']} & {rng('first')} / {rng('mid')} / {rng('last')} & "
                    f"L{peak['L']} ({peak['third']}) & {peak['bias']:.4f} & "
                    + " / ".join((r"\textbf{%.4f}" % means[t]) if t == argmin else f"{means[t]:.4f}"
                                 for t in ("first", "mid", "last"))
                    + f" & {argmin} \\\\")
    return rows, stat

# ══════════════════ X-4 ══════════════════════════════════════
CATS = ["Age","Disability_status","Gender_identity","Nationality","Physical_appearance",
        "Race_ethnicity","Race_x_SES","Race_x_gender","Religion","SES","Sexual_orientation"]
CATLBL = {"Disability_status":"Disability","Physical_appearance":"Phys.\\ appearance",
          "Race_ethnicity":"Race/ethnicity","Race_x_SES":"Race $\\times$ SES",
          "Race_x_gender":"Race $\\times$ gender","Sexual_orientation":"Sexual orient.",
          "Gender_identity":"Gender identity"}

def build_x4():
    per, rows = {}, []
    models = [(n, bd) for n, _, bd, _ in NEW_MODELS]
    for name, bd in models:
        bycat = {c: bbq_metrics(bd, f"only_{c}")["by_category"] for c in ("first", "mid", "last")}
        per[name] = {cat: min(("first", "mid", "last"),
                              key=lambda t: bycat[t][cat]["ambig"]["bias_score"]) for cat in CATS}
    for cat in CATS:
        w = [per[n][cat] for n, _ in models]
        rows.append(f"{CATLBL.get(cat, cat)} & " + " & ".join(
            (r"\textbf{mid}" if x == "mid" else x) for x in w) +
            f" & {w.count('mid')}/{len(models)} \\\\")
    tot = sum(v.count("mid") for v in
              [[per[n][c] for c in CATS] for n, _ in models])
    mid_cats = sum(1 for cat in CATS
                   if sum(per[n][cat] == "mid" for n, _ in models) > len(models) / 2)
    return rows, [n for n, _ in models], tot, mid_cats

# ══════════════════ Z ════════════════════════════════════════
ALL_MMLU = [("Qwen2.5-0.5B","qwen_0.5b"),("Qwen2.5-1.5B","qwen_1.5b"),("Qwen2.5-3B","qwen_3b"),
            ("Qwen2.5-14B","qwen_14b"),("Gemma-2-2B","gemma_2b"),("Gemma-2-9B","gemma_9b"),
            ("Gemma-3-12B","gemma3_12b"),("Llama-3.2-1B","llama32_1b"),("Llama-3.2-3B","llama32_3b"),
            ("Llama-3.1-8B","llama31_8b"),("Llama-3-8B","llama3_8b")]
FAMILY = lambda n: ("Gemma" if n.startswith("Gemma") else
                    "Llama" if n.startswith("Llama") else
                    "Qwen"  if n.startswith("Qwen")  else
                    "Mistral" if n.startswith("Mistral") else "DeepSeek")

def build_z():
    rows, byfam = [], {}
    src = [(n, f"{BLOCK}/{a}") for n, a in ALL_MMLU] + \
          [(n, md) for n, _, _, md in NEW_MODELS if md]
    for name, d in src:
        full = mmlu(d, "full")
        if full is None:
            continue
        dm = {c: mmlu(d, f"minus_{c}") for c in ("first", "mid", "last")}
        if dm["first"] is None:
            continue
        df, dmid = (dm["first"] - full) * 100, (dm["mid"] - full) * 100
        byfam.setdefault(FAMILY(name), []).append(df)
        rows.append(f"{name} & {FAMILY(name)} & {full*100:.1f} & ${df:+.1f}$ & ${dmid:+.1f}$ & "
                    + ("---" if dm["last"] is None else f"${(dm['last']-full)*100:+.1f}$") + r" \\")
    return rows, byfam

if __name__ == "__main__":
    print("== integrity ==")
    rb, rm, audit, verdict = build_x1()
    for n, t in audit:
        assert t == [58492], (n, t)
    print(f"  X-1: {len(NEW_MODELS)} models x 7 conditions, BBQ total = 58,492 everywhere  OK")
    nec = sum(v[2] for v in verdict); suf = sum(v[1] for v in verdict)
    print(f"  X-1 verdict: necessity {nec}/{len(NEW_MODELS)}, "
          f"sufficiency {suf}/{len(NEW_MODELS)} "
          f"(fail: {[v[0] for v in verdict if not v[1]]})")

    ry, n_excl, n_pos = build_y()
    print(f"  Y: excludes-0 {n_excl} | positive-and-significant {n_pos}")
    r2, s2 = build_x2()
    print(f"  X-2: {[(k, v['argmin'], 'L%d' % v['peak'], v['peak_third']) for k, v in s2.items()]}")
    r4, m4, tot4, midcats = build_x4()
    print(f"  X-4: mid-lowest in {tot4}/{11*len(m4)} model-category cells; "
          f"majority-mid categories {midcats}/11")
    rz, byfam = build_z()
    print(f"  Z: {len(rz)} models | mean dMMLU(-first) by family: "
          f"{ {k: round(sum(v)/len(v),1) for k,v in byfam.items()} }")

    print("\n== writing ==")
    W("tab_x1_bbq.tex",  "\n".join(rb))
    W("tab_x1_mmlu.tex", "\n".join(rm))
    W("tab_y_ci.tex",    "\n".join(ry))
    W("tab_x2.tex",      "\n".join(r2))
    W("tab_x4.tex",      "\n".join(r4))
    W("tab_z.tex",       "\n".join(rz))
